// Loads the artwork a design draws from; `onReady` runs once it arrives so
// the caller can draw again.
export function loadDesignImages(base, onReady) {
  for (const key of ["printyours"]) {
    if (DESIGN_IMAGES[key]) continue;
    const image = new Image();
    image.onload = () => { for (const fn of waiting) fn(); };
    image.src = `${base}/${key}.png`;
    DESIGN_IMAGES[key] = image;
  }
  waiting.add(onReady);
  return () => waiting.delete(onReady);
}

// Diameter of the circle artwork-backed designs are laid out in.
function designSide(w, h) {
  const ring = RINGS[activeRing];
  return ring ? 2 * ringRadius(w, h) * (ring.inner - 0.02) : Math.min(w, h) * 0.96 * 0.94;
}

function readyDesignImage(key) {
  const image = DESIGN_IMAGES[key];
  return image && image.complete && image.naturalWidth ? image : null;
}

// `scale` shrinks the art about the centre, leaving room for something round it.
function drawDesignImage(g, w, h, key, scale = 1) {
  const image = readyDesignImage(key);
  if (!image) return;
  const side = designSide(w, h) * scale;
  g.imageSmoothingEnabled = true;
  g.imageSmoothingQuality = "high";
  g.drawImage(image, (w - side) / 2, (h - side) / 2, side, side);
}

// Where the two halves of the logo sit in printyours.png, as [x, y, w, h] in
