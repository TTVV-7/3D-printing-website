// Radial stroke from radius r0 out to r1 at angle a.
function ringTick(g, r0, r1, a) {
  ringPoly(g, [[r0, a], [r1, a]]);
  g.stroke();
}

// Starts a path through [radius, angle] points; the caller fills or strokes it.
function ringPoly(g, pts) {
  g.beginPath();
  for (const [r, a] of pts) g.lineTo(r * Math.cos(a), r * Math.sin(a));
}

function ringArc(g, r, a0 = 0, a1 = Math.PI * 2) {
  g.beginPath();
  g.arc(0, 0, r, a0, a1);
  g.stroke();
}

// Calls fn(angle, stepAngle, index) n times round the circle, starting at 12 o'clock.
function ringSteps(n, fn) {
  const step = (Math.PI * 2) / n;
  for (let i = 0; i < n; i++) fn(i * step - Math.PI / 2, step, i);
}

// The radius ring fractions are measured against: maskPath's circle (0.96),
// pushed out 3% so a ring's outer edge (0.96 of this) lands just inside the
// cut line instead of leaving a visible band of white beyond it.
function ringRadius(w, h) {
  return Math.min(w, h) / 2 * 0.96 * 1.03;
}


export function drawEdgeRing(g, w, h, key, mask) {
  const ring = RINGS[key];
  if (!ring) return;
  const R = ringRadius(w, h);
  g.save();
  if (mask) g.clip(mask);
  g.translate(w / 2, h / 2);
  // White frame from the ring outward, so the ring stays legible over dense
  // patterns and photos instead of fighting whatever is underneath it.
  g.beginPath();
  g.rect(-w / 2, -h / 2, w, h);
  g.arc(0, 0, ring.inner * R, 0, Math.PI * 2);
  g.fillStyle = "#fff";
  g.fill("evenodd");
  g.fillStyle = "#000";
  g.strokeStyle = "#000";
  g.lineCap = "butt";
  g.setLineDash([]);
  ring.draw(g, R, (f) => Math.max(1.5, f * R));
  g.restore();
}

