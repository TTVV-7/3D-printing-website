const LOGO_FRAME = 1304;
const LOGO_MARK = [330, 129, 644, 702];
const LOGO_WORD = [103, 860, 1100, 141];

// Draws one piece of the logo `height` tall, centred on (cx, cy) in g's current frame.
function drawLogoPart(g, image, part, cx, cy, height) {
  const k = image.naturalWidth / LOGO_FRAME;
  const [sx, sy, sw, sh] = part.map((v) => v * k);
  const width = height * (sw / sh);
  g.drawImage(image, sx, sy, sw, sh, cx - width / 2, cy - height / 2, width, height);
}

// Bends the wordmark round an arc of radius r (to the letters' mid-height)
// by drawing it as thin upright slices, each turned to its place on the
// circle. The top arc reads clockwise; the bottom arc is flipped so it still
// reads left to right with the letters' feet pointing outward.
function drawLogoWordArc(g, image, r, height, bottom) {
  const k = image.naturalWidth / LOGO_FRAME;
  const [sx, sy, sw, sh] = LOGO_WORD.map((v) => v * k);
  const span = (height * (sw / sh)) / r;
  const n = Math.ceil((r + height / 2) * span * 1.5);
  const dw = ((r + height / 2) * span) / n + 0.75; // slight overlap hides the seams
  for (let i = 0; i < n; i++) {
    const t = (i + 0.5) / n;
    g.save();
    g.rotate((bottom ? -1 : 1) * (t - 0.5) * span);
    g.drawImage(image, sx + (i / n) * sw, sy, sw / n, sh, -dw / 2, (bottom ? r : -r) - height / 2, dw, height);
    g.restore();
  }
}


