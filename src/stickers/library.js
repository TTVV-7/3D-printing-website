// Returns a path for the given shape, fit inside a w x h box, or null for
// "none". `p` is anything with moveTo/lineTo/arc/closePath: a Path2D by
// default, or an adapter (the 3D view builds its outline through one).
// Returns a Path2D for the given shape, fit inside a w x h box, or null for "none".
export function maskPath(shape, w, h, seed, p = new Path2D()) {
  if (shape === "none") return null;
  const cx = w / 2, cy = h / 2;
  const R = Math.min(w, h) / 2 * 0.96;

  const polar = (rFn, steps = 240, phase = -Math.PI / 2) => {
    for (let i = 0; i <= steps; i++) {
      const t = (i / steps) * Math.PI * 2 + phase;
      const r = rFn(t) * R;
      const x = cx + r * Math.cos(t), y = cy + r * Math.sin(t);
      if (i === 0) p.moveTo(x, y); else p.lineTo(x, y);
    }
    p.closePath();
  };

  if (shape === "circle") {
    p.arc(cx, cy, R, 0, Math.PI * 2);
  } else if (shape === "squircle") {
    // superellipse |x|^4 + |y|^4 = 1
    polar((t) => {
      const c = Math.abs(Math.cos(t)), s = Math.abs(Math.sin(t));
      return Math.pow(c ** 4 + s ** 4, -0.25);
    });
  } else if (shape === "heart") {
    // classic parametric heart, normalized to fill the box
    const pts = [];
    let minX = 1e9, maxX = -1e9, minY = 1e9, maxY = -1e9;
    for (let i = 0; i <= 240; i++) {
      const t = (i / 240) * Math.PI * 2;
      const x = 16 * Math.sin(t) ** 3;
      const y = -(13 * Math.cos(t) - 5 * Math.cos(2 * t) - 2 * Math.cos(3 * t) - Math.cos(4 * t));
      pts.push([x, y]);
      minX = Math.min(minX, x); maxX = Math.max(maxX, x);
      minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
    const s = (2 * R) / Math.max(maxX - minX, maxY - minY);
    const ox = (minX + maxX) / 2, oy = (minY + maxY) / 2;
    pts.forEach(([x, y], i) => {
      const px = cx + (x - ox) * s, py = cy + (y - oy) * s;
      if (i === 0) p.moveTo(px, py); else p.lineTo(px, py);
    });
    p.closePath();
  } else if (shape === "star") {
    const rand = rng(seed);
    const n = 5 + Math.floor(rand() * 3); // 5-7 points
    const inner = 0.42 + rand() * 0.12;
    for (let i = 0; i < n * 2; i++) {
      const t = (i / (n * 2)) * Math.PI * 2 - Math.PI / 2;
      const r = (i % 2 === 0 ? 1 : inner) * R;
      const x = cx + r * Math.cos(t), y = cy + r * Math.sin(t);
      if (i === 0) p.moveTo(x, y); else p.lineTo(x, y);
    }
    p.closePath();
  } else if (shape === "pebble") {
    const rand = rng(seed);
    const harmonics = [];
    for (let k = 2; k <= 5; k++) {
      harmonics.push([k, (rand() * 0.22) / (k - 1), rand() * Math.PI * 2]);
    }
    polar((t) => {
      let r = 0.88;
      for (const [k, amp, ph] of harmonics) r += amp * Math.sin(k * t + ph);
      return r;
    });
  } else if (shape === "scallop") {
    const rand = rng(seed);
    const lobes = 8 + Math.floor(rand() * 6);
    polar((t) => 0.93 + 0.07 * Math.cos(lobes * t), 360);
  } else if (shape === "burst") {
    const rand = rng(seed);
    const n = 12 + Math.floor(rand() * 8);
    polar((t) => 0.9 + 0.1 * Math.abs(Math.sin((n * t) / 2)) ** 0.5, 480);
  } else {
    // unrecognised shape: fall back to no crop. Returning the empty Path2D
    // would clip everything away and blank both preview and export.
    return null;
  }
  return p;
}

